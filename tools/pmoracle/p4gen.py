#!/usr/bin/env python3
"""p4gen.py — writes p4test.asm, the Pentium 4's transcript image (SSE2):
double precision — every packed and scalar arithmetic instruction over
eight operand pairs (zeros, denormals, infinities, quiet and signalling
NaNs, the extremes, random doubles), register and memory forms, again
under each rounding mode and with flush-to-zero; CMPPD/CMPSD's eight
predicates, COMISD/UCOMISD, the moves and shuffles, the conversions
among singles, doubles and integers; the 128-bit integer forms of the
MMX instructions and SSE2's own (PSHUFD/HW/LW, PSRLDQ/PSLLDQ,
PUNPCK*QDQ, PADDQ/PSUBQ/PMULUDQ, MOVQ2DQ/MOVDQ2Q, MASKMOVDQU, MOVNTDQ,
MOVNTI); then by hand: CPUID (the CLFLUSH line), CLFLUSH, LFENCE,
MFENCE, PAUSE, the MXCSR mask, reserved prefixes. SSE itself is
p3test.asm's (p3gen.py), not repeated. p3gen.py's frame. Run by
pgrun.py --mp4 (against Bochs's p4_willamette).

    python3 p4gen.py > p4test.asm
"""
import random, struct
random.seed(2001)

p3 = open("p3gen.py").read()
# the frame and its two-head loader, the table runners and printers: p3gen.py's
exec(p3[p3.index("frame = open("):p3.index("def f(x):")])
doc = __doc__.split("\n\n")[0].replace("p4gen.py — writes p4test.asm,", "p4test.asm — generated by p4gen.py:")
head = "".join("; " + l + "\n" for l in doc.split("\n")) + "        cpu willamette\n" + head[head.index("        org 0x7C00"):]
rest = rest.replace('msg_start db "p3test"', 'msg_start db "p4test"')

def d(x): return struct.unpack("<Q", struct.pack("<d", x))[0]
special = [0, 1 << 63, d(1.0), d(-1.0), d(1.5), d(3.0), 1, 0x8008000000000000, 0x0010000000000000,
           0x7FEFFFFFFFFFFFFF, 0x7FF0000000000000, 0xFFF0000000000000, 0x7FF8000000000000, 0x7FF0000000000001,
           0xFFF8000000000000, d(0.1), d(1e300), d(1e-300), d(-2.5), d(1e39), d(1e-40), d(3.4e38)]
def rnd():
    r = random.random()
    if r < 0.5: return random.choice(special)
    return d(random.uniform(-1e6, 1e6)) if r < 0.85 else random.getrandbits(64)
pairs = [([d(1.0), d(-3.0)], [d(3.0), d(0.0)]),
         ([0x7FF8000000000000, 0x7FF0000000000001], [0x7FF8000000000012, 0xFFF0000000000000]),
         ([1, 0x8008000000000000], [d(1.0), 0x0010000000000000]),
         ([0x7FEFFFFFFFFFFFFF, d(1e39)], [d(2.0), d(1e-40)])]
while len(pairs) < 8:
    pairs.append(([rnd(), rnd()], [rnd(), rnd()]))

code = []
k = 0
def new(body):
    global k
    k += 1
    code.append("x%d:\n%s\n        ret" % (k, body))
    return "x%d" % k
main = []
for m in ["sqrt", "add", "mul", "sub", "min", "div", "max"]:
    for sfx in ("pd", "sd"):
        main.append(new("        %s%s xmm0, xmm1" % (m, sfx)))
        main.append(new("        %s%s xmm0, [edi + 16]" % (m, sfx)))
for m in ("andpd", "andnpd", "orpd", "xorpd", "unpcklpd", "unpckhpd"):
    main.append(new("        %s xmm0, xmm1" % m))
    main.append(new("        %s xmm0, [edi + 16]" % m))
for im in range(4):
    main.append(new("        shufpd xmm0, xmm1, %d" % im))
for p in range(8):
    main.append(new("        cmppd xmm0, xmm1, %d" % p))
    main.append(new("        cmpsd xmm0, [edi + 16], %d" % p))
for m in ("comisd", "ucomisd"):
    main.append(new("        mov dword [tmpi], 0x8D7\n        push dword [tmpi]\n        popfd\n        %s xmm0, xmm1\n        pushfd\n        pop eax\n        and eax, 0x8D5\n        mov [tmpi], eax\n        movss xmm0, [tmpi]" % m))
for body in ("movapd xmm0, [edi + 16]", "movupd xmm0, [edi + 8]", "movsd xmm0, [edi + 16]", "movsd xmm0, xmm1",
             "movlpd xmm0, [edi + 16]", "movhpd xmm0, [edi + 24]", "movmskpd eax, xmm1\n        mov [tmpi], eax\n        movss xmm0, [tmpi]",
             "movhpd [tmpx], xmm1\n        movlpd [tmpx + 8], xmm0\n        movapd xmm0, [tmpx]",
             "movntpd [tmpx], xmm1\n        movapd xmm0, [tmpx]", "movsd [tmpx], xmm1\n        movapd xmm0, [tmpx]",
             # the conversions
             "cvtps2pd xmm0, xmm1", "cvtps2pd xmm0, [edi + 16]", "cvtpd2ps xmm0, xmm1", "cvtpd2ps xmm0, [edi + 16]",
             "cvtss2sd xmm0, xmm1", "cvtss2sd xmm0, [edi + 20]", "cvtsd2ss xmm0, xmm1", "cvtsd2ss xmm0, [edi + 16]",
             "cvtdq2ps xmm0, xmm1", "cvtps2dq xmm0, xmm1", "cvttps2dq xmm0, [edi + 16]",
             "cvtdq2pd xmm0, xmm1", "cvtdq2pd xmm0, [edi + 24]", "cvtpd2dq xmm0, xmm1", "cvttpd2dq xmm0, [edi + 16]",
             "cvtsi2sd xmm0, [edi + 16]", "mov eax, [edi + 20]\n        cvtsi2sd xmm0, eax",
             "cvtsd2si eax, xmm1\n        mov [tmpi], eax\n        movss xmm0, [tmpi]",
             "cvttsd2si eax, [edi + 16]\n        mov [tmpi], eax\n        movss xmm0, [tmpi]",
             "cvtpi2pd xmm0, [edi + 16]", "movq mm1, [edi + 24]\n        cvtpi2pd xmm0, mm1\n        emms",
             "cvtpd2pi mm2, xmm1\n        movq [tmpq], mm2\n        movlpd xmm0, [tmpq]\n        emms",
             "cvttpd2pi mm2, [edi + 16]\n        movq [tmpq], mm2\n        movlpd xmm0, [tmpq]\n        emms"):
    main.append(new("        " + body))
rc = []
for m in ("add", "sub", "mul", "div", "sqrt"):
    rc.append(new("        %spd xmm0, xmm1" % m))
    rc.append(new("        %ssd xmm0, [edi + 16]" % m))
rc.append(new("        cvtpd2ps xmm0, xmm1"))
rc.append(new("        cvtpd2dq xmm0, xmm1"))
ints = []
for m in ("punpcklbw", "punpcklwd", "punpckldq", "punpcklqdq", "punpckhbw", "punpckhwd", "punpckhdq", "punpckhqdq",
          "packsswb", "packssdw", "packuswb", "pcmpgtb", "pcmpgtw", "pcmpgtd", "pcmpeqb", "pcmpeqw", "pcmpeqd",
          "paddb", "paddw", "paddd", "paddq", "psubb", "psubw", "psubd", "psubq", "paddsb", "paddsw", "paddusb",
          "paddusw", "psubsb", "psubsw", "psubusb", "psubusw", "pmullw", "pmulhw", "pmulhuw", "pmuludq", "pmaddwd",
          "pand", "pandn", "por", "pxor", "pavgb", "pavgw", "pminub", "pminsw", "pmaxub", "pmaxsw", "psadbw"):
    ints.append(new("        %s xmm0, xmm1" % m))
    ints.append(new("        %s xmm0, [edi + 16]" % m))
for m in ("psrlw", "psrld", "psrlq", "psraw", "psrad", "psllw", "pslld", "psllq"):
    for n in (0, 3, 17, 33, 64):
        ints.append(new("        mov dword [tmpq], %d\n        mov dword [tmpq + 4], 0\n        movq xmm1, [tmpq]\n        %s xmm0, xmm1" % (n, m)))
    for n in (1, 15, 31, 200):
        ints.append(new("        %s xmm0, %d" % (m, n)))
for m in ("psrldq", "pslldq"):
    for n in (0, 1, 7, 15, 16):
        ints.append(new("        %s xmm0, %d" % (m, n)))
for body in ("pshufd xmm0, xmm1, 0x1B", "pshufd xmm0, [edi + 16], 0x4E", "pshufhw xmm0, xmm1, 0x1B", "pshuflw xmm0, [edi + 16], 0xB1",
             "movdqa xmm0, [edi + 16]", "movdqu xmm0, [edi + 4]", "movq xmm0, xmm1", "movq xmm0, [edi + 24]",
             "movd xmm0, [edi + 20]", "mov eax, [edi + 24]\n        movd xmm0, eax",
             "movd eax, xmm1\n        mov [tmpi], eax\n        movss xmm0, [tmpi]",
             "movq [tmpx], xmm1\n        movdqa xmm0, [tmpx]", "movdqu [tmpx + 1], xmm1\n        movdqu xmm0, [tmpx]",
             "movntdq [tmpx], xmm1\n        movdqa xmm0, [tmpx]", "mov eax, [edi + 20]\n        movnti [tmpx + 4], eax\n        movdqa xmm0, [tmpx]",
             "pmovmskb eax, xmm1\n        mov [tmpi], eax\n        movss xmm0, [tmpi]",
             "pextrw eax, xmm1, 5\n        mov [tmpi], eax\n        movss xmm0, [tmpi]", "pinsrw xmm0, [edi + 18], 6",
             "mov eax, [edi + 20]\n        pinsrw xmm0, eax, 1",
             "movdqa [tmpx], xmm0\n        mov edi, tmpx\n        maskmovdqu xmm1, xmm1\n        movdqa xmm0, [tmpx]",
             "movq mm3, [edi + 16]\n        movq2dq xmm0, mm3\n        emms",
             "movdq2q mm3, xmm1\n        movq [tmpq], mm3\n        movlpd xmm0, [tmpq]\n        emms",
             "movq mm0, [edi]\n        paddq mm0, [edi + 16]\n        movq [tmpq], mm0\n        movlpd xmm0, [tmpq]\n        emms",
             "movq mm0, [edi]\n        psubq mm0, [edi + 16]\n        movq [tmpq], mm0\n        movlpd xmm0, [tmpq]\n        emms",
             "movq mm0, [edi]\n        movq mm1, [edi + 16]\n        pmuludq mm0, mm1\n        movq [tmpq], mm0\n        movlpd xmm0, [tmpq]\n        emms"):
    ints.append(new("        " + body))

out = [head, """
        ; ---- CPUID
        mov byte [tno], 1
        mov eax, 1
        cpuid
        call ok_eax
        mov byte [tno], 2
        mov eax, 1
        cpuid
        mov eax, edx
        call ok_eax
        mov byte [tno], 3
        mov eax, 1
        cpuid
        mov eax, ebx
        and eax, 0xFF00                     ; the CLFLUSH line, in 8-byte units
        call ok_eax
        mov byte [tno], 4
        mov eax, 2
        cpuid
        call ok_eax
        mov byte [tno], 5
        mov eax, 2
        cpuid
        mov eax, edx
        call ok_eax

        mov eax, cr4
        or eax, 0x600
        mov cr4, eax
        mov dword [qno], 0
        mov dword [cur_mx], 0x1F80
        mov esi, main_stubs
        call run_table
        mov esi, rc_stubs
        mov dword [cur_mx], 0x3F80
        call run_table
        mov dword [cur_mx], 0x5F80
        mov esi, rc_stubs
        call run_table
        mov dword [cur_mx], 0x7F80
        mov esi, rc_stubs
        call run_table
        mov dword [cur_mx], 0x9F80
        mov esi, rc_stubs
        call run_table
        mov dword [cur_mx], 0x1FC0          ; DAZ
        mov esi, rc_stubs
        call run_table
        mov esi, main_stubs                 ; and every one under DAZ
        call run_table
        mov dword [cur_mx], 0x1F80
        mov esi, int_stubs
        call run_table

        ; ---- by hand
        mov byte [tno], 0x40
        mov dword [resume], .t41
        clflush [pairs]
        mov eax, 1
        call ok_eax
.t41:   mov byte [tno], 0x41
        mov dword [resume], .t42
        clflush [0x1000000]                 ; not present: #PF
        call ok_eax
.t42:   mov byte [tno], 0x42
        mov dword [resume], .t43
        lfence
        mfence
        pause
        mov eax, 2
        call ok_eax
.t43:   mov byte [tno], 0x43                ; the MXCSR mask: FXSAVE's
        mov dword [resume], .t44
        fxsave [fxarea]
        mov eax, [fxarea + 28]
        call ok_eax
.t44:   mov byte [tno], 0x44                ; DAZ: a reserved bit (#GP) or not
        mov dword [resume], .t45
        mov dword [tmpi], 0x1FC0
        ldmxcsr [tmpi]
        stmxcsr [tmpi]
        mov eax, [tmpi]
        call ok_eax
.t45:   mov dword [tmpi], 0x1F80
        ldmxcsr [tmpi]
        mov byte [tno], 0x45
        mov dword [resume], .t46
        db 0xF3, 0x0F, 0xFC, 0xC1           ; F3 on PADDB: reserved
        call ok_eax
.t46:   mov byte [tno], 0x46
        mov dword [resume], .t47
        mov eax, cr4
        and eax, ~0x200
        mov cr4, eax
        paddb xmm0, xmm1                    ; OSFXSR clear: #UD
        call ok_eax
.t47:   mov eax, cr4
        or eax, 0x200
        mov cr4, eax
        mov byte [tno], 0x47
        mov dword [resume], .t48
        movdqa xmm0, [pairs + 8]            ; #GP
        call ok_eax
.t48:   mov byte [tno], 0x48
        mov dword [resume], .t49
        paddb xmm0, [pairs + 8]             ; #GP
        call ok_eax
.t49:   mov byte [tno], 0x49
        mov dword [resume], .t4a
        mov dword [tmpi], 0x1D80            ; ZE unmasked
        ldmxcsr [tmpi]
        movapd xmm0, [pairs]
        xorpd xmm1, xmm1
        divpd xmm0, xmm1                    ; #XM
        call ok_eax
.t4a:   mov dword [tmpi], 0x1F80
        ldmxcsr [tmpi]
        jmp t60_done

run_table:                                  ; ESI: stubs; each over each pair
.op:    mov ebx, [esi]
        test ebx, ebx
        jz .d
        mov edi, pairs
        mov ecx, NPAIRS
.pair:  movaps xmm0, [edi]
        movaps xmm1, [edi + 16]
        ldmxcsr [cur_mx]
        push edi
        push ecx
        call ebx
        pop ecx
        pop edi
        call pr_x0
        add edi, 32
        loop .pair
        add esi, 4
        jmp .op
.d:     ret
"""]
out.append(mid)
out.append(p3[p3.index('out.append("""pr_x0:') + len('out.append("""'):p3.index('""")\nout.append("\\n".join(code)')])
out.append("\n".join(code) + "\n")
data = "main_stubs:\n" + "".join("        dd %s\n" % s for s in main) + "        dd 0\n"
data += "rc_stubs:\n" + "".join("        dd %s\n" % s for s in rc) + "        dd 0\n"
data += "int_stubs:\n" + "".join("        dd %s\n" % s for s in ints) + "        dd 0\n"
data += "NPAIRS equ %d\n        align 16\npairs:\n" % len(pairs)
for a, b in pairs:
    data += "        dq " + ", ".join("0x%016X" % v for v in a) + "\n"
    data += "        dq " + ", ".join("0x%016X" % v for v in b) + "\n"
data += "        align 16\ntmpx:     times 8 dd 0\n        align 16\nfxarea:   times 512 db 0\n"
out.append(data)
rest = rest.replace("flg       dd 0", """flg       dd 0
qno       dd 0
tmpi      dd 0
tmpm      dd 0
cur_mx    dd 0x1F80
          align 8
tmpq      dq 0
msg_x     db "X", 0
msg_q     db "Q", 0""")
out.append(rest)
print("".join(out), end="")
