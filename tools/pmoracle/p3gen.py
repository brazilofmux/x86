#!/usr/bin/env python3
"""p3gen.py — writes p3test.asm, the Pentium III's transcript image (SSE):
every packed and scalar arithmetic instruction over eight operand pairs
(zeros, denormals, infinities, quiet and signalling NaNs, the extremes,
random singles), in register and memory form; ADD/SUB/MUL/DIV/SQRT again
under each rounding mode and with flush-to-zero; CMPPS/CMPSS on all eight
predicates; COMISS/UCOMISS; the conversions both ways; the moves,
shuffles, unpacks and logicals; RCPPS/RSQRTPS (their low 12 significand
bits masked: the approximation is the part's own); the MMX additions;
then by hand: FXSAVE/FXRSTOR, LDMXCSR/STMXCSR, the alignment #GP, #XM and
#UD for an unmasked exception, CR4.OSFXSR, CR0.EM and CR0.TS, SSE2's
prefixes (#UD). c686test.asm's frame, read from both heads of track 0.
Run by pgrun.py --mp3 (against Bochs's p3_katmai).

    python3 p3gen.py > p3test.asm
"""
import random, struct
random.seed(1999)

frame = open("c686test.asm").read()
head_end = frame.index("        mov esi, msg_start\n        call puts\n") + len("        mov esi, msg_start\n        call puts\n")
tail_start = frame.index(".t60:   xor eax, eax")
r3_start = frame.index("r3_rdpmc:")
r3_end = frame.index("if_probe:")
head, mid, rest = frame[:head_end], frame[tail_start:r3_start], frame[r3_end:]
doc = __doc__.split("\n\n")[0].replace("p3gen.py — writes p3test.asm,", "p3test.asm — generated by p3gen.py:")
head = head.replace(head[:head.index("        org 0x7C00")], "".join("; " + l + "\n" for l in doc.split("\n")) + "        cpu katmai\n")
head = head.replace("STAGE2_SECS equ 16", "STAGE2_SECS equ 35")
# stage 1: sectors 2-18 of head 0, then 1-18 of head 1
head = head.replace("""        mov ah, 0x02
        mov al, STAGE2_SECS
        mov ch, 0
        mov cl, 2
        mov dh, 0
        mov bx, STAGE2_LMA
        int 0x13
        jc  .h""", """        mov ax, 0x0211                  ; 17 sectors: 2-18, head 0
        mov cx, 0x0002
        mov dx, 0x0000
        mov bx, STAGE2_LMA
        int 0x13
        jc  .h
        mov ax, 0x0212                  ; 18: 1-18, head 1
        mov cx, 0x0001
        mov dx, 0x0100
        mov bx, STAGE2_LMA + 17 * 512
        int 0x13
        jc  .h""")
mid = mid.replace(".t60:   xor eax, eax", "t60_done:\n.t60:   xor eax, eax")
rest = rest.replace('msg_start db "c686test"', 'msg_start db "p3test"')

def f(x): return struct.unpack("<I", struct.pack("<f", x))[0]
special = [0, 0x80000000, f(1.0), f(-1.0), f(1.5), f(3.0), 0x00000001, 0x80400000, 0x00800000, 0x7F7FFFFF,
           0x7F800000, 0xFF800000, 0x7FC00000, 0x7F800001, 0xFFC00000, f(0.1), f(1e30), f(1e-30), f(-2.5), f(7.0)]
def rnd():
    r = random.random()
    if r < 0.5: return random.choice(special)
    return f(random.uniform(-1e4, 1e4)) if r < 0.85 else random.getrandbits(32)
pairs = [([f(1.0), f(2.0), f(-3.0), f(0.5)], [f(3.0), f(-2.0), f(0.0), f(7.0)]),
         ([0x7FC00000, 0x7F800001, f(1.0), 0x7F800000], [f(1.0), 0x7FC00012, 0x7F800001, 0xFF800000]),
         ([0x00000001, 0x80400000, 0x00800000, f(0.0)], [f(1.0), 0x00000002, f(0.5), 0x80000000]),
         ([0x7F7FFFFF, 0x00800000, f(1e30), f(-1.0)], [f(2.0), f(0.25), f(1e30), f(0.0)])]
while len(pairs) < 8:
    pairs.append(([rnd() for _ in range(4)], [rnd() for _ in range(4)]))

arith = ["sqrt", "add", "mul", "sub", "min", "div", "max"]
stubs, code = [], []
def stub(name, body):
    code.append("%s:\n%s\n        ret" % (name, body))
    return name
k = 0
def new(body):
    global k
    k += 1
    return stub("x%d" % k, body)
main = []
for m in arith:
    for sfx in ("ps", "ss"):
        main.append(new("        %s%s xmm0, xmm1" % (m, sfx)))
        main.append(new("        %s%s xmm0, [edi + 16]" % (m, sfx)))
for m in ("rcp", "rsqrt"):
    for sfx in ("ps", "ss"):
        main.append(new("        %s%s xmm0, xmm1\n        andps xmm0, [m_approx]" % (m, sfx)))
for m in ("andps", "andnps", "orps", "xorps", "unpcklps", "unpckhps"):
    main.append(new("        %s xmm0, xmm1" % m))
    main.append(new("        %s xmm0, [edi + 16]" % m))
for im in (0x1B, 0xE4, 0x4E, 0xB1):
    main.append(new("        shufps xmm0, xmm1, 0x%02X" % im))
for p in range(8):
    main.append(new("        cmpps xmm0, xmm1, %d" % p))
    main.append(new("        cmpss xmm0, [edi + 16], %d" % p))
for m in ("comiss", "ucomiss"):
    main.append(new("        mov dword [tmpi], 0x8D7\n        push dword [tmpi]\n        popfd\n        %s xmm0, xmm1\n        pushfd\n        pop eax\n        and eax, 0x8D5\n        mov [tmpi], eax\n        movss xmm0, [tmpi]" % m))
main.append(new("        movaps xmm0, [edi + 16]"))
main.append(new("        movups xmm0, [edi + 12]"))
main.append(new("        movss xmm0, [edi + 16]"))
main.append(new("        movss xmm0, xmm1"))
main.append(new("        movlps xmm0, [edi + 16]"))
main.append(new("        movhps xmm0, [edi + 16]"))
main.append(new("        movhlps xmm0, xmm1"))
main.append(new("        movlhps xmm0, xmm1"))
main.append(new("        movmskps eax, xmm1\n        mov [tmpi], eax\n        movss xmm0, [tmpi]"))
main.append(new("        movaps [tmpx], xmm1\n        movaps xmm0, [tmpx]"))
main.append(new("        movntps [tmpx], xmm1\n        movaps xmm0, [tmpx]"))
main.append(new("        movhps [tmpx], xmm1\n        movlps [tmpx + 8], xmm0\n        movaps xmm0, [tmpx]"))
main.append(new("        cvtsi2ss xmm0, [edi + 16]"))
main.append(new("        mov eax, [edi + 20]\n        cvtsi2ss xmm0, eax"))
main.append(new("        cvtpi2ps xmm0, [edi + 16]"))
main.append(new("        movq mm1, [edi + 24]\n        cvtpi2ps xmm0, mm1\n        emms"))
for m in ("cvtss2si", "cvttss2si"):
    main.append(new("        %s eax, xmm1\n        mov [tmpi], eax\n        movss xmm0, [tmpi]" % m))
    main.append(new("        %s eax, [edi + 20]\n        mov [tmpi], eax\n        movss xmm0, [tmpi]" % m))
for m in ("cvtps2pi", "cvttps2pi"):
    main.append(new("        %s mm2, xmm1\n        movq [tmpq], mm2\n        movlps xmm0, [tmpq]\n        emms" % m))
    main.append(new("        %s mm2, [edi + 24]\n        movq [tmpq], mm2\n        movlps xmm0, [tmpq]\n        emms" % m))
rc = []
for m in ("add", "sub", "mul", "div", "sqrt"):
    rc.append(new("        %sps xmm0, xmm1" % m))
    rc.append(new("        %sss xmm0, [edi + 16]" % m))
mmx = []
for body in ("pshufw mm0, mm1, 0x1B", "pshufw mm0, [edi + 16], 0xE4", "pinsrw mm0, [edi + 18], 2",
             "mov eax, [edi + 20]\n        pinsrw mm0, eax, 3", "pextrw eax, mm1, 1\n        movd mm0, eax",
             "pmovmskb eax, mm1\n        movd mm0, eax", "pminub mm0, mm1", "pmaxub mm0, [edi + 16]", "pminsw mm0, mm1",
             "pmaxsw mm0, mm1", "pavgb mm0, mm1", "pavgw mm0, [edi + 16]", "pmulhuw mm0, mm1", "psadbw mm0, mm1",
             "movntq [tmpq], mm1\n        movq mm0, [tmpq]",
             "movq [tmpq], mm0\n        mov edi, tmpq\n        maskmovq mm1, mm1\n        movq mm0, [tmpq]"):
    mmx.append(new("        " + body))

out = [head, """
        ; ---- CPUID
        mov byte [tno], 1
        mov eax, 1
        cpuid
        call ok_eax
        mov byte [tno], 2
        mov eax, 1
        cpuid
        mov eax, edx
        call ok_eax
        mov byte [tno], 3
        mov eax, 2
        cpuid
        mov eax, edx
        call ok_eax

        ; ---- SSE on: CR4.OSFXSR and OSXMMEXCPT
        mov eax, cr4
        or eax, 0x600
        mov cr4, eax
        mov byte [tno], 4
        stmxcsr [tmpi]
        mov eax, [tmpi]                     ; 1F80 at reset
        call ok_eax
        mov dword [qno], 0

        ; ---- each stub over each pair: X<n> xmm0 (lanes 3..0) and MXCSR
        mov dword [cur_mx], 0x1F80
        mov esi, main_stubs
        call run_table
        mov esi, rc_stubs                   ; the rounding modes, and FTZ
        mov dword [cur_mx], 0x3F80
        call run_table
        mov dword [cur_mx], 0x5F80
        mov esi, rc_stubs
        call run_table
        mov dword [cur_mx], 0x7F80
        mov esi, rc_stubs
        call run_table
        mov dword [cur_mx], 0x9F80
        mov esi, rc_stubs
        call run_table
        mov dword [cur_mx], 0x1F80
        mov esi, mmx_stubs                  ; the MMX additions: Q<n> mm0
        call run_mmx
        emms

        ; ---- unmasked exceptions: #XM (OSXMMEXCPT), #UD without it; the destination kept
        mov byte [tno], 0x40
        mov dword [resume], .t41
        movaps xmm0, [pairs]
        xorps xmm1, xmm1
        mov dword [tmpi], 0x1D80            ; ZE unmasked
        ldmxcsr [tmpi]
        divps xmm0, xmm1
        call ok_eax
.t41:   mov byte [tno], 0x41
        stmxcsr [tmpi]
        mov eax, [tmpi]                     ; ZE set
        call ok_eax
        mov byte [tno], 0x42
        movss [tmpi], xmm0
        mov eax, [tmpi]                     ; xmm0 as it was
        call ok_eax
        mov byte [tno], 0x43
        mov dword [resume], .t44
        mov eax, cr4
        and eax, ~0x400
        mov cr4, eax
        divps xmm0, xmm1                    ; #UD
        call ok_eax
.t44:   mov eax, cr4
        or eax, 0x400
        mov cr4, eax
        mov dword [tmpi], 0x1F80
        ldmxcsr [tmpi]
        mov byte [tno], 0x44
        mov dword [resume], .t45
        mov dword [tmpi], 0x10000           ; a reserved bit: #GP
        ldmxcsr [tmpi]
        call ok_eax
.t45:   mov byte [tno], 0x45
        mov dword [resume], .t46
        mov dword [tmpi], 0xFFBF            ; every writable bit
        ldmxcsr [tmpi]
        stmxcsr [tmpi]
        mov eax, [tmpi]
        call ok_eax
.t46:   mov dword [tmpi], 0x1F80
        ldmxcsr [tmpi]

        ; ---- alignment, CR4.OSFXSR, CR0.EM, CR0.TS, SSE2's prefixes
        mov byte [tno], 0x50
        mov dword [resume], .t51
        movaps xmm0, [pairs + 4]            ; #GP
        call ok_eax
.t51:   mov byte [tno], 0x51
        mov dword [resume], .t52
        addps xmm0, [pairs + 4]             ; #GP
        call ok_eax
.t52:   mov byte [tno], 0x52
        mov dword [resume], .t53
        addss xmm0, [pairs + 4]             ; scalar: fine
        call ok_eax
.t53:   mov byte [tno], 0x53
        mov dword [resume], .t54
        mov eax, cr4
        and eax, ~0x200
        mov cr4, eax
        addps xmm0, xmm1                    ; OSFXSR clear: #UD
        call ok_eax
.t54:   mov byte [tno], 0x54
        mov dword [resume], .t55
        stmxcsr [tmpi]                      ; #UD too
        call ok_eax
.t55:   mov eax, cr4
        or eax, 0x200
        mov cr4, eax
        mov byte [tno], 0x55
        mov dword [resume], .t56
        mov eax, cr0
        or eax, 4
        mov cr0, eax
        addps xmm0, xmm1                    ; EM: #UD
        call ok_eax
.t56:   mov eax, cr0
        and eax, ~4
        mov cr0, eax
        mov byte [tno], 0x56
        mov dword [resume], .t57
        mov eax, cr0
        or eax, 8
        mov cr0, eax
        addps xmm0, xmm1                    ; TS: #NM
        call ok_eax
.t57:   clts
        mov byte [tno], 0x57
        mov dword [resume], .t58
        db 0x66, 0x0F, 0x58, 0xC1           ; addpd: #UD on a Pentium III
        call ok_eax
.t58:   mov byte [tno], 0x58
        mov dword [resume], .t59
        db 0xF2, 0x0F, 0x58, 0xC1           ; addsd
        call ok_eax
.t59:   mov byte [tno], 0x59
        mov dword [resume], .t5a
        sfence
        mov eax, 1
        call ok_eax
.t5a:   mov byte [tno], 0x5A
        mov dword [resume], .t60
        prefetchnta [pairs]
        prefetcht0 [0x1000000]              ; not present: no fault
        mov eax, 2
        call ok_eax

        ; ---- FXSAVE / FXRSTOR: the image over a filled area, then back
.t60:   mov edi, fxarea
        mov ecx, 512 / 4
        mov eax, 0xA5A5A5A5
        rep stosd
        finit
        fld1
        fldpi                               ; two registers, TOP 6
        movaps xmm3, [pairs + 32]
        mov dword [tmpi], 0x3F81            ; RC down, IE set
        ldmxcsr [tmpi]
        fxsave [fxarea]
        mov esi, fxarea
        mov ecx, 0
.fx:    mov byte [tno], 0x70
        mov eax, [esi]
        call ok_eax
        add esi, 4
        inc ecx
        cmp ecx, 300 / 4
        jb .fx
        mov byte [tno], 0x71
        finit
        xorps xmm3, xmm3
        mov dword [tmpi], 0x1F80
        ldmxcsr [tmpi]
        fxrstor [fxarea]
        stmxcsr [tmpi]
        mov eax, [tmpi]                     ; 3F81 again
        call ok_eax
        mov byte [tno], 0x72
        movss [tmpi], xmm3
        mov eax, [tmpi]
        call ok_eax
        mov byte [tno], 0x73
        fnstsw ax
        call ok_eax
        mov byte [tno], 0x74
        fstp dword [tmpi]                   ; pi
        mov eax, [tmpi]
        call ok_eax
        mov byte [tno], 0x75
        mov dword [resume], .t76
        fxsave [fxarea + 8]                 ; misaligned: #GP
        call ok_eax
.t76:   mov byte [tno], 0x76
        mov dword [resume], .t77
        mov dword [fxarea + 24], 0x10000    ; a reserved MXCSR bit: #GP
        fxrstor [fxarea]
        call ok_eax
.t77:   mov byte [tno], 0x77                ; OSFXSR clear: the SSE part not saved
        mov dword [resume], t60_done
        mov edi, fxarea
        mov ecx, 512 / 4
        mov eax, 0xA5A5A5A5
        rep stosd
        mov eax, cr4
        and eax, ~0x200
        mov cr4, eax
        fxsave [fxarea]
        mov eax, cr4
        or eax, 0x200
        mov cr4, eax
        mov eax, [fxarea + 24]
        call ok_eax
        mov byte [tno], 0x78
        mov eax, [fxarea + 160]
        call ok_eax
        mov byte [tno], 0x79
        mov eax, [fxarea + 32]
        call ok_eax
        finit
        jmp t60_done

run_table:                                  ; ESI: stubs; each over each pair
.op:    mov ebx, [esi]
        test ebx, ebx
        jz .d
        mov edi, pairs
        mov ecx, NPAIRS
.pair:  movaps xmm0, [edi]
        movaps xmm1, [edi + 16]
        ldmxcsr [cur_mx]
        push edi
        push ecx
        call ebx
        pop ecx
        pop edi
        call pr_x0
        add edi, 32
        loop .pair
        add esi, 4
        jmp .op
.d:     ret
run_mmx:
.op:    mov ebx, [esi]
        test ebx, ebx
        jz .d
        mov edi, pairs
        mov ecx, NPAIRS
.pair:  movq mm0, [edi]
        movq mm1, [edi + 16]
        push edi
        push ecx
        call ebx
        pop ecx
        pop edi
        call pr_mm0
        add edi, 32
        loop .pair
        add esi, 4
        jmp .op
.d:     ret
"""]
out.append(mid)
out.append("""pr_x0:                                      ; "X<n> " lanes 3..0, MXCSR; then MXCSR back to cur_mx
        pushad
        movups [tmpx], xmm0
        stmxcsr [tmpm]
        mov esi, msg_x
        call puts
        mov eax, [qno]
        call hex16
        mov ebx, 12
.l:     mov al, ' '
        out 0xE9, al
        mov eax, [tmpx + ebx]
        call hex32
        sub ebx, 4
        jns .l
        mov al, ' '
        out 0xE9, al
        mov eax, [tmpm]
        call hex32
        mov al, 10
        out 0xE9, al
        ldmxcsr [cur_mx]
        inc dword [qno]
        popad
        ret
pr_mm0:
        pushad
        movq [tmpq], mm0
        mov esi, msg_q
        call puts
        mov eax, [qno]
        call hex16
        mov al, ' '
        out 0xE9, al
        mov eax, [tmpq + 4]
        call hex32
        mov eax, [tmpq]
        call hex32
        mov al, 10
        out 0xE9, al
        inc dword [qno]
        popad
        ret
""")
out.append("\n".join(code) + "\n")
data = "main_stubs:\n" + "".join("        dd %s\n" % s for s in main) + "        dd 0\n"
data += "rc_stubs:\n" + "".join("        dd %s\n" % s for s in rc) + "        dd 0\n"
data += "mmx_stubs:\n" + "".join("        dd %s\n" % s for s in mmx) + "        dd 0\n"
data += "NPAIRS equ %d\n        align 16\npairs:\n" % len(pairs)
for a, b in pairs:
    data += "        dd " + ", ".join("0x%08X" % v for v in a) + "\n"
    data += "        dd " + ", ".join("0x%08X" % v for v in b) + "\n"
data += "m_approx: times 4 dd 0xFFFFF000\n"
data += "tmpx:     times 4 dd 0\n        align 16\nfxarea:   times 512 db 0\n"
out.append(data)
rest = rest.replace("flg       dd 0", """flg       dd 0
qno       dd 0
tmpi      dd 0
tmpm      dd 0
cur_mx    dd 0x1F80
          align 8
tmpq      dq 0
msg_x     db "X", 0
msg_q     db "Q", 0""")
out.append(rest)
print("".join(out), end="")
