#!/usr/bin/env python3
"""p2gen.py — writes p2test.asm, the Pentium II's transcript image: every
MMX instruction over eight operand pairs (register and memory forms, the
shifts by register and by immediate, counts past the lane), MOVD both
ways; then by hand: the tag word and TOP after MMX and after EMMS, what
the x87 sees in a register MMX wrote, #UD (CR0.EM), #NM (CR0.TS) and #MF
(a pending x87 exception) on an MMX instruction, SYSENTER and SYSEXIT
(the segments, ESP, EIP, IF; #GP with no selector and SYSEXIT at ring 3).
c686test.asm's frame. Run by pgrun.py --mp2 (against Bochs's
p2_klamath).

    python3 p2gen.py > p2test.asm
"""
import random
random.seed(1997)

frame = open("c686test.asm").read()
head_end = frame.index("        mov esi, msg_start\n        call puts\n") + len("        mov esi, msg_start\n        call puts\n")
tail_start = frame.index(".t60:   xor eax, eax")
r3_start = frame.index("r3_rdpmc:")
r3_end = frame.index("if_probe:")
head, mid, rest = frame[:head_end], frame[tail_start:r3_start], frame[r3_end:]
head = head.replace(head[:head.index("        org 0x7C00")], (__doc__.split("\n\n")[0].replace('"""', '').replace("p2gen.py — writes p2test.asm", "p2test.asm — generated by p2gen.py:")
        .replace("\n", "\n; ").join([";", ""])) + "\n        cpu p2\n")
head = head.replace("STAGE2_SECS equ 16", "STAGE2_SECS equ 17")
mid = mid.replace(".t60:   xor eax, eax", "t60_done:\n.t60:   xor eax, eax")
rest = rest.replace('msg_start db "c686test"', 'msg_start db "p2test"')

# operand pairs: edge values and random ones
edge = [0, 0xFFFFFFFFFFFFFFFF, 0x8000800080008000, 0x7FFF7FFF7FFF7FFF, 0x80007FFF0001FFFF, 0x7F80FF0100FE8081]
pairs = [(edge[0], edge[1]), (edge[2], edge[3]), (edge[4], edge[5]), (edge[5], edge[2])]
while len(pairs) < 8:
    pairs.append((random.getrandbits(64), random.getrandbits(64)))
counts = [0, 1, 7, 15, 16, 31, 32, 63, 64, 0x10000000000]

ops = [  # mnemonic, 64-bit memory form (False: m32)
    ("punpcklbw", False), ("punpcklwd", False), ("punpckldq", False), ("packsswb", True), ("pcmpgtb", True),
    ("pcmpgtw", True), ("pcmpgtd", True), ("packuswb", True), ("punpckhbw", True), ("punpckhwd", True),
    ("punpckhdq", True), ("packssdw", True), ("pcmpeqb", True), ("pcmpeqw", True), ("pcmpeqd", True),
    ("pmullw", True), ("psubusb", True), ("psubusw", True), ("pand", True), ("paddusb", True), ("paddusw", True),
    ("pandn", True), ("pmulhw", True), ("psubsb", True), ("psubsw", True), ("por", True), ("paddsb", True),
    ("paddsw", True), ("pxor", True), ("pmaddwd", True), ("psubb", True), ("psubw", True), ("psubd", True),
    ("paddb", True), ("paddw", True), ("paddd", True), ("movq", True),
]
shifts = ["psrlw", "psrld", "psrlq", "psraw", "psrad", "psllw", "pslld", "psllq"]

out = [head]
out.append("""
        ; ---- CPUID: the signature, the features, leaf 2
        mov byte [tno], 1
        mov eax, 1
        cpuid
        call ok_eax
        mov byte [tno], 2
        mov eax, 1
        cpuid
        mov eax, edx
        call ok_eax
        mov byte [tno], 3
        mov eax, 2
        cpuid
        call ok_eax
        mov byte [tno], 4
        mov eax, 2
        cpuid
        mov eax, edx
        call ok_eax

        ; ---- MMX: each stub over each operand pair; Q<n> is mm0 after it
        mov dword [qno], 0
        mov esi, stubs
.op:    mov ebx, [esi]
        test ebx, ebx
        jz .shifts
        mov edi, pairs
        mov ecx, NPAIRS
.pair:  movq mm0, [edi]
        movq mm1, [edi + 8]
        call ebx
        call pr_mm0
        add edi, 16
        loop .pair
        add esi, 4
        jmp .op
.shifts:                                    ; by mm1 = each count, and by Ib
        mov esi, shstubs
.sop:   mov ebx, [esi]
        test ebx, ebx
        jz .imm
        mov edi, counts
        mov ecx, NCOUNTS
.cnt:   movq mm0, [pairs + 32]
        movq mm1, [edi]
        call ebx
        call pr_mm0
        add edi, 8
        loop .cnt
        add esi, 4
        jmp .sop
.imm:   mov esi, imstubs
.iop:   mov ebx, [esi]
        test ebx, ebx
        jz .hand
        movq mm0, [pairs + 32]
        call ebx
        call pr_mm0
        add esi, 4
        jmp .iop
.hand:
        ; ---- MOVD
        mov byte [tno], 0x60
        movq mm1, [pairs + 40]
        movd eax, mm1
        call ok_eax
        mov byte [tno], 0x61
        mov eax, 0x89ABCDEF
        movq mm0, [pairs + 16]
        movd mm0, eax                       ; zero-extended
        call pr_mm0
        mov byte [tno], 0x62
        movd mm0, [0x30000]
        call pr_mm0
        mov byte [tno], 0x63
        movd [tmp], mm1
        mov eax, [tmp]
        call ok_eax
        mov byte [tno], 0x64
        movq [tmpq], mm1
        mov eax, [tmpq + 4]
        call ok_eax

        ; ---- the x87's view: TOP and the tag word after MMX, after EMMS
        mov byte [tno], 0x70
        finit
        fld1
        fld1                                ; TOP 6, two tags valid
        movq mm2, [pairs + 32]
        fnstenv [env]
        mov eax, [env + 4]                  ; status word: TOP 0
        shl eax, 16
        mov ax, [env + 8]                   ; tag word: all valid
        call ok_eax
        mov byte [tno], 0x71
        emms
        fnstenv [env]
        mov eax, [env + 4]
        shl eax, 16
        mov ax, [env + 8]                   ; all empty
        call ok_eax
        mov byte [tno], 0x72                ; ST(0) after MMX wrote R0: exponent all ones
        finit
        movq mm0, [pairs + 32]
        fstp tword [tbuf]
        movzx eax, word [tbuf + 8]
        call ok_eax
        mov byte [tno], 0x73
        mov eax, [tbuf + 4]
        call ok_eax
        mov byte [tno], 0x74                ; an x87 load, read as MMX: the significand
        finit
        fld1
        movq [tmpq], mm7                    ; R7 = ST(0) (TOP 7)
        mov eax, [tmpq + 4]
        call ok_eax
        emms

        ; ---- exceptions: CR0.EM, CR0.TS, a pending x87 exception
        mov byte [tno], 0x80
        mov dword [resume], .t81
        mov eax, cr0
        or eax, 4                           ; EM
        mov cr0, eax
        paddb mm0, mm1                      ; #UD
        call ok_eax
.t81:   mov eax, cr0
        and eax, ~4
        mov cr0, eax
        mov byte [tno], 0x81
        mov dword [resume], .t82
        mov eax, cr0
        or eax, 8                           ; TS
        mov cr0, eax
        paddb mm0, mm1                      ; #NM
        call ok_eax
.t82:   clts
        mov byte [tno], 0x82
        mov dword [resume], .t83
        mov eax, cr0
        or eax, 0x20                        ; NE: #MF, not FERR#
        mov cr0, eax
        finit
        fldcw [cw_ze]
        fldz
        fld1
        fdiv st0, st1                       ; 1/0, ZE unmasked: pending
        paddb mm0, mm1                      ; #MF
        call ok_eax
.t83:   fnclex
        finit
        emms

        ; ---- SYSENTER / SYSEXIT
        mov byte [tno], 0x90
        mov dword [resume], .t91
        xor eax, eax
        xor edx, edx
        mov ecx, 0x174
        wrmsr                               ; no selector:
        sysenter                            ; #GP
        call ok_eax
.t91:   mov ecx, 0x174
        mov eax, SEL_CODE
        xor edx, edx
        wrmsr
        mov ecx, 0x175
        mov eax, 0x6C00
        wrmsr
        mov ecx, 0x176
        mov eax, sys_in
        wrmsr
        mov byte [tno], 0x91
        mov ecx, 0x174
        rdmsr
        call ok_eax
        mov byte [tno], 0x9A
        mov ebx, r3_sysexit                 ; SYSEXIT at ring 3: #GP
        call ring3
        mov [saved_esp], esp                ; the round trip, last: ring 3 by SYSEXIT, back by SYSENTER
        mov dword [resume], t60_done
        mov ax, SEL_DATA3
        mov ds, ax
        mov es, ax
        mov ecx, 0x5800                     ; ESP at ring 3
        mov edx, r3_sys                     ; EIP
        sti
        sysexit                             ; to ring 3 (r3_sys): CS 1B, SS 23; back by SYSENTER to sys_in
""")
out.append(mid)
out.append("""r3_rdpmc:       xor ecx, ecx
                rdpmc
                int RET_VEC
r3_sys:         mov eax, cs                 ; ring 3 after SYSEXIT
                mov ebx, ss
                mov edi, esp
                sysenter                    ; and back: sys_in at ring 0
sys_in:
        mov si, SEL_DATA
        mov ds, si
        mov es, si
        mov byte [tno], 0x92
        call ok_eax                         ; the ring-3 CS
        mov byte [tno], 0x93
        mov eax, ebx                        ; its SS
        call ok_eax
        mov byte [tno], 0x94
        mov eax, edi                        ; its ESP
        call ok_eax
        mov byte [tno], 0x96
        mov eax, cs
        call ok_eax
        mov byte [tno], 0x97
        mov eax, ss
        call ok_eax
        mov byte [tno], 0x98
        mov eax, esp
        call ok_eax
        mov byte [tno], 0x99
        pushfd
        pop eax
        and eax, 0x200                      ; IF cleared
        call ok_eax
        mov esp, [saved_esp]
        jmp t60_done
r3_sysexit:     sysexit
                int RET_VEC
pr_mm0:                                     ; "Q<n> " mm0, all registers kept
        pushad
        movq [tmpq], mm0
        mov esi, msg_q
        call puts
        mov eax, [qno]
        call hex16
        mov al, ' '
        out 0xE9, al
        mov eax, [tmpq + 4]
        call hex32
        mov eax, [tmpq]
        call hex32
        mov al, 10
        out 0xE9, al
        inc dword [qno]
        popad
        ret
""")
st = ["stubs:"]
code = []
for i, (m, q) in enumerate(ops):
    code.append("s_r%d:  %s mm0, mm1\n        ret" % (i, m))
    code.append("s_m%d:  %s mm0, [edi + 8]\n        ret" % (i, m))
    st.append("        dd s_r%d, s_m%d" % (i, i))
st.append("        dd 0")
sh = ["shstubs:"]
for i, m in enumerate(shifts):
    code.append("h_r%d:  %s mm0, mm1\n        ret" % (i, m))
    sh.append("        dd h_r%d" % i)
sh.append("        dd 0")
im = ["imstubs:"]
k = 0
for m in shifts:
    for n in (0, 1, 9, 15, 17, 31, 33, 63, 64, 200):
        code.append("i_%d:   %s mm0, %d\n        ret" % (k, m, n))
        im.append("        dd i_%d" % k)
        k += 1
im.append("        dd 0")
out.append("\n".join(code) + "\n")
data = "\n".join(st + sh + im) + "\n"
data += "NPAIRS equ %d\nNCOUNTS equ %d\n        align 8\npairs:\n" % (len(pairs), len(counts))
for a, b in pairs:
    data += "        dq 0x%016X, 0x%016X\n" % (a, b)
data += "counts:\n" + "".join("        dq 0x%X\n" % n for n in counts)
rest = rest.replace("flg       dd 0", """flg       dd 0
qno       dd 0
tmpq      dq 0
env       times 28 db 0
tbuf      times 10 db 0
cw_ze     dw 0x037B                       ; ZE unmasked
msg_q     db "Q", 0""")
out.append(data)
out.append(rest)
print("".join(out), end="")
